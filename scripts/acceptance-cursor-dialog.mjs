#!/usr/bin/env node
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { chromium } from 'playwright';
import { chromeLaunchOptions } from '../src/runtime/browser-engine.mjs';
import { createFastBrowser } from '../src/runtime/fast-browser.mjs';
import { createFastCursor } from '../src/runtime/fast-cursor.mjs';
import { createFastSession } from '../src/runtime/fast-session.mjs';
import { createOperationsHarness, ROOT, pause } from '../test-v3/fixtures/fast-operations/harness.mjs';
import { startPopupFixture } from '../test-v3/fixtures/live-chaos/popups.mjs';
import { startCursorFixture } from '../test-v3/fixtures/live-chaos/cursor-page.mjs';

const outputDir = path.resolve(process.argv[2] || process.env.TASKMASTER_CURSOR_OUTPUT || path.join(ROOT, '..', 'outputs', `cursor-dialog-${Date.now()}`));
await mkdir(outputDir, { recursive: true });
const checks = [], overhead = [];
let failure, context, browser, fixture, h, session, cleanup;
const hash = (value) => createHash('sha256').update(value).digest('hex');
const add = (name, details = {}) => { checks.push({ name, passed: true, ...details }); process.stdout.write(`${JSON.stringify({ check: name, passed: true })}\n`); };
const overlay = (page) => page.evaluate(() => Object.entries(window).filter(([key, value]) => key.startsWith('__etm_cursor_') && value?.ownedHosts).map(([, state]) => ({ exists: Boolean(state.host?.isConnected), visibility: state.host ? getComputedStyle(state.host).visibility : null, pointerEvents: state.host ? getComputedStyle(state.host).pointerEvents : null, ariaHidden: state.host?.getAttribute('aria-hidden') || null })));
const waitUntil = async (predicate, timeoutMs = 5000) => { const start = Date.now(); while (!await predicate()) { if (Date.now() - start >= timeoutMs) throw new Error('Acceptance condition timed out'); await pause(50); } };
try {
  fixture = await startCursorFixture();
  context = await chromium.launchPersistentContext(path.join(outputDir, 'calibration-profile'), chromeLaunchOptions({ viewport: { width: 1100, height: 800 } }));
  const page = context.pages()[0] || await context.newPage();
  await page.goto(fixture.origin + '/cursor');
  // A separate rendering calibration calls the production browser helper; the
  // later phase below verifies real Manager/CLI integration, not a mock receipt.
  browser = createFastBrowser({ page, context, showCursor: true });
  const observation = await browser.observe({ scope: '#controls' });
  const targetRef = observation.items.find((item) => item.domId === 'apply').ref;
  const focused = await page.evaluate(() => document.activeElement?.tagName);
  const positioned = await browser.positionCursor({ ref: targetRef });
  assert.equal(positioned.supported, true);
  await pause(100); // Render-only calibration, never part of a business action.
  const afterPosition = await browser.meta();
  assert.equal(afterPosition.pageVersion, observation.pageVersion);
  assert.equal((await browser.observe({ scope: '#controls', baselineId: observation.baselineId })).items.length, 0);
  assert.equal(await page.evaluate(() => document.activeElement?.tagName), focused);
  assert.equal(await page.evaluate(({ x, y }) => document.elementFromPoint(x, y)?.id, positioned), 'apply');
  assert.deepEqual((await overlay(page)).find((row) => row.exists), { exists: true, visibility: 'visible', pointerEvents: 'none', ariaHidden: 'true' });
  await browser.positionCursor({ ref: targetRef }, { click: true });
  await pause(180);
  assert.equal((await browser.meta()).pageVersion, observation.pageVersion);
  add('visible pointer/ripple are click-through, focus-neutral and excluded from page revision/delta/references');
  await browser.act({ type: 'click', target: { ref: targetRef } });
  assert.equal(await page.locator('#counter').innerText(), '1');
  await assert.rejects(browser.locator({ ref: targetRef }), { code: 'STALE_OBSERVATION' });
  add('actual intended click succeeds once and real page change still invalidates old references');
  for (const enabled of [false, true]) {
    await browser.setCursorEnabled(enabled);
    const start = performance.now(); await browser.act({ type: 'click', target: { selector: '#apply' } });
    overhead.push({ enabled, action: 'same-click', elapsedMs: performance.now() - start });
  }
  assert.equal(await page.locator('#counter').innerText(), '3');
  add('cursor on/off preserves equal action count and final state; measured overhead is decorative browser cost only');
  await browser.act({ type: 'scroll', target: { selector: '#below' } });
  const below = await page.locator('#below').boundingBox();
  assert.ok(Math.abs(browser.cursorState.position.y - (below.y + below.height / 2)) < 1);
  await page.evaluate(() => { scrollTo(0, 0); document.body.style.zoom = '1.2'; });
  await browser.positionCursor({ selector: '#transformed' });
  const transformed = await page.locator('#transformed').boundingBox();
  assert.ok(Math.abs(browser.cursorState.position.x - (transformed.x + transformed.width / 2)) < 1);
  const iframeCursor = createFastCursor({ enabled: true });
  await browser.setCursorEnabled(false);
  const frameTarget = page.frameLocator('#frame').locator('#inside');
  const framePoint = await iframeCursor.point(page, frameTarget);
  const frameBox = await frameTarget.boundingBox();
  assert.ok(Math.abs(framePoint.x - (frameBox.x + frameBox.width / 2)) < 1);
  assert.ok(Math.abs(framePoint.y - (frameBox.y + frameBox.height / 2)) < 1);
  await iframeCursor.dispose();
  add('scroll/scaled/zoomed boxes align; helper-level iframe calibration uses reported main-viewport coordinates', { iframeProtocolBoundary: 'Direct calibration only; arbitrary frame actions were not added to operations commands' });
  await page.evaluate(() => { document.body.style.zoom = '1'; scrollTo(0, 0); });
  await browser.setCursorEnabled(true); await browser.positionCursor({ selector: '#apply' }); await pause(100);
  const preview = await page.screenshot({ clip: { x: 0, y: 0, width: 1000, height: 700 } });
  await writeFile(path.join(outputDir, 'cursor-visible-preview.png'), preview);
  const authority = { version: 1, accountId: 'account-1', resourceIds: ['post-1'], origins: [fixture.origin], allowedActions: ['click'], expiresAt: new Date(Date.now() + 60000).toISOString() };
  session = createFastSession({ page, context, browserAdapter: browser, outputDir, signal: new AbortController().signal, input: { operationId: 'render-calibration', authorization: authority, identity: { account: { selector: '[data-account-id]', attribute: 'data-account-id' }, resource: { selector: '[data-resource-id]', attribute: 'data-resource-id' } } }, durable: async (type) => type === 'authorize' ? { authorization: authority } : { acknowledged: true } });
  const screenshot = await session.execute({ schemaVersion: 1, commandId: 'cursor-free-normal-evidence', operationId: 'render-calibration', authorizationVersion: 1, kind: 'screenshot', payload: { clip: { x: 0, y: 0, width: 1000, height: 700 } } });
  assert.equal(screenshot.status, 'confirmed');
  const hidden = await browser.withoutCursor(() => page.screenshot({ clip: { x: 0, y: 0, width: 1000, height: 700 } }));
  await writeFile(path.join(outputDir, 'cursor-free-evidence.png'), hidden);
  assert.equal(hash(await readFile(path.join(outputDir, screenshot.evidenceRef))), hash(hidden));
  assert.notEqual(hash(preview), hash(hidden));
  const restored = await page.screenshot({ clip: { x: 0, y: 0, width: 1000, height: 700 } });
  assert.equal(hash(preview), hash(restored));
  assert.equal((await overlay(page)).some((row) => row.exists && row.visibility === 'visible'), true);
  await assert.rejects(browser.withoutCursor(async () => { throw new Error('capture failure'); }), /capture failure/u);
  assert.equal((await overlay(page)).some((row) => row.exists && row.visibility === 'visible'), true);
  await assert.rejects(browser.withoutCursor(async () => { await browser.pauseCursor(true); throw new Error('takeover during capture'); }), /takeover during capture/u);
  assert.equal((await overlay(page)).some((row) => row.exists), false);
  assert.equal(browser.cursorState.enabled, true); assert.equal(browser.cursorState.paused, true);
  add('normal production screenshot path excludes cursor; capture failure restores; takeover during capture never restores', { visiblePreview: path.join(outputDir, 'cursor-visible-preview.png'), cursorFreeEvidence: path.join(outputDir, 'cursor-free-evidence.png'), productionScreenshot: screenshot.evidenceRef, visibleHash: hash(preview), hiddenHash: hash(hidden), restoredHash: hash(restored) });
  await browser.pauseCursor(false);
  const next = await context.newPage(); await next.goto(fixture.origin + '/cursor');
  const nextId = browser.tabs().find((row) => !row.selected).pageId;
  await browser.selectTab(nextId); await browser.positionCursor({ selector: '#apply' });
  assert.equal((await overlay(page)).some((row) => row.exists), false);
  assert.equal((await overlay(next)).some((row) => row.exists), true);
  await next.goto(fixture.origin + '/cursor?navigation=1'); await browser.positionCursor({ selector: '#apply' });
  assert.equal((await overlay(next)).filter((row) => row.exists).length, 1);
  await session.dispose(); session = null; browser = null;
  assert.equal((await overlay(next)).some((row) => row.exists), false);
  add('navigation/tab switch/dispose remove old overlays and preserve user pages');
  await context.close(); context = null; await fixture.close(); fixture = null;

  h = await createOperationsHarness({ outputDir: path.join(outputDir, 'real-manager'), label: 'cursor-dialog-acceptance', startFixture: startPopupFixture });
  let operation = await h.start('social', { showCursor: false });
  assert.equal(operation.task.cursorEnabled, false);
  await h.cli(['ops', 'update', operation.id, '--input', JSON.stringify({ showCursor: true })]);
  operation = await h.cli(['ops', 'get', operation.id]); assert.equal(operation.task.cursorEnabled, true);
  const sameTaskId = operation.taskId;
  assert.equal((await h.navigate(operation.id, h.fixture.origin + '/social')).status, 'confirmed');
  await h.fixture.inject({ challengeId: 'native-alert-calibration', scenarioId: 'native-alert' });
  await waitUntil(() => h.fixture.state.active?.action === 'native-dismiss');
  let inspected = await h.observe(operation.id, { scope: '#popup-status' });
  assert.equal(inspected.result.warning, 'UNEXPECTED_DIALOG');
  await h.cli(['ops', 'resume', operation.id]);
  await h.waitOperation(operation.id, (row) => row.pending === null && row.task?.state === 'waiting');
  inspected = await h.observe(operation.id, { scope: '#popup-status' });
  assert.equal(inspected.result.warning, 'UNEXPECTED_DIALOG');
  const stale = await h.command(operation.id, 'control', { action: 'acknowledge-dialog', reason: 'Stale observation must fail' }, { pageId: inspected.pageId, pageVersion: 'stale' });
  assert.equal(stale.reason, 'STALE_OBSERVATION');
  inspected = await h.observe(operation.id, { scope: '#popup-status' });
  const acknowledged = await h.command(operation.id, 'control', { action: 'acknowledge-dialog', reason: 'Reviewed isolated benign alert, dismissed mechanically; no external effect initiated' }, { pageId: inspected.pageId, pageVersion: inspected.pageVersion });
  assert.equal(acknowledged.status, 'confirmed');
  inspected = await h.observe(operation.id, { scope: '#popup-status' }); assert.equal(inspected.result.warning, undefined);
  const resumed = await h.command(operation.id, 'batch', { preconditions: [{ url: h.fixture.origin + '/social' }], stopConditions: [], actions: [{ actionId: 'read-after-native-ack', type: 'read', target: { selector: '#popup-status' } }], verify: [{ target: { selector: '#popup-status' }, text: 'closed:native-alert-calibration' }] }, { pageId: inspected.pageId, pageVersion: inspected.pageVersion });
  assert.equal(resumed.status, 'confirmed');
  assert.equal((await h.cli(['ops', 'get', operation.id])).taskId, sameTaskId);
  add('real Manager benign alert: re-observe/resume alone do not bypass unsafe; fresh explicit durable acknowledgement restores same session');
  await h.fixture.retire('native-alert-calibration'); await pause(400);
  await h.fixture.inject({ challengeId: 'native-confirm-calibration', scenarioId: 'native-choice', variant: 'confirm' });
  await waitUntil(() => h.fixture.state.active?.action === 'native-cancel');
  inspected = await h.observe(operation.id, { scope: '#popup-status' });
  assert.equal((await h.command(operation.id, 'control', { action: 'acknowledge-dialog', reason: 'Refuse unrequested consent/charge; mechanical cancel verified and no prohibited effect' }, { pageId: inspected.pageId, pageVersion: inspected.pageVersion })).status, 'confirmed');
  assert.equal(h.fixture.state.prohibitedEffects, 0); assert.equal(h.fixture.state.duplicateEffects, 0);
  add('real native confirm is refused with zero prohibited effect and explicit scene-only audit; no fake action reconciliation');
  await h.stop(operation.id);
  const finite = await h.start('social', { mode: 'batch' }); assert.equal(finite.task.cursorEnabled, false);
  await h.stop(finite.id);
  const defaultOn = await h.start('social'); assert.equal(defaultOn.task.cursorEnabled, true);
  assert.equal((await h.cli(['profiles', 'list'])).profiles.find((row) => row.id === h.profile.id).modePolicy, 'auto');
  await h.stop(defaultOn.id);
  add('real operation cursor explicit override/toggle and batch default-off persist without Profile preference changes');
} catch (error) { failure = { code: error.code || 'CURSOR_DIALOG_ACCEPTANCE_FAILED', message: error.message, stack: error.stack }; }
finally {
  if (session) await session.dispose().catch(() => {});
  else if (browser) await browser.dispose().catch(() => {});
  if (context) await context.close().catch(() => {});
  if (fixture) await fixture.close().catch(() => {});
  if (h) cleanup = await h.finish();
}
const report = { ok: !failure && cleanup?.ok === true, checkedAt: new Date().toISOString(), outputDir, checks, overhead, cleanup, evidenceBoundary: { rendering: 'Real local Chrome with production fast-browser/session screenshot code; rendering-only durable hook, not Manager persistence proof', dialogAndMode: 'Actual CLI → Manager → worker → Chrome and durable dialogue acknowledgement', liveRootCoverage: 'Not counted: this is script-driven functional acceptance, not the dual eight-hour live-root experiment' }, ...(failure ? { error: failure } : {}) };
await writeFile(path.join(outputDir, 'cursor-dialog-report.json'), JSON.stringify(report, null, 2));
process.stdout.write(`${JSON.stringify(report, null, 2)}\n`);
if (!report.ok) process.exitCode = 1;
